def _direct_gsmooth_python_result() -> GSmoothResult:
    inp = _direct_gsmooth_inputs()
    return gsmooth(
        temperature_1e4K=float(inp["temperature_1e4K"]),
        turbulent_velocity_km_s=float(inp["turbulent_velocity_km_s"]),
        epi_eV=inp["epi"],
        opakc_before=inp["opakc"],
        rccemis_before=inp["rccemis"],
        brcems_before=inp["brcems"],
        ncn2=int(inp["ncn2"]),
    )


def run_direct_fortran_gsmooth_validation(
    *, rtol: float = 2.0e-14, atol: float = 1.0e-30
) -> Mapping[str, object]:
    """Compare the Python wrapper against frozen direct-original-Fortran output."""
    inp = _direct_gsmooth_inputs()
    refs = direct_fortran_gsmooth_reference_case()
    result = _direct_gsmooth_python_result()
    n = int(inp["ncn2"])

    vtherm_ready = bool(
        np.isclose(result.vtherm_cm_s, refs["vtherm_cm_s"], rtol=rtol, atol=atol)
    )
    brcems_ready = bool(
        np.allclose(result.brcems_after[:n], refs["brcems_active"], rtol=rtol, atol=atol)
    )
    rcc1_ready = bool(
        np.allclose(result.rccemis_after[0, :n], refs["rcc1_active"], rtol=rtol, atol=atol)
    )
    rcc2_ready = bool(
        np.allclose(result.rccemis_after[1, :n], refs["rcc2_active"], rtol=rtol, atol=atol)
    )
    opakc_ready = bool(
        np.allclose(result.opakc_after[:n], refs["opakc_active"], rtol=rtol, atol=atol)
    )
    first_two_ready = bool(
        np.array_equal(result.brcems_after[:2], result.brcems_before[:2])
        and np.array_equal(result.rccemis_after[:, :2], result.rccemis_before[:, :2])
        and np.array_equal(result.opakc_after[:2], result.opakc_before[:2])
    )
    high_energy_ready = bool(
        np.array_equal(result.brcems_after[12:n], result.brcems_before[12:n])
        and np.array_equal(result.rccemis_after[:, 12:n], result.rccemis_before[:, 12:n])
        and np.array_equal(result.opakc_after[12:n], result.opakc_before[12:n])
    )
    tails_ready = bool(
        np.array_equal(result.brcems_after[n:], result.brcems_before[n:])
        and np.array_equal(result.rccemis_after[:, n:], result.rccemis_before[:, n:])
        and np.array_equal(result.opakc_after[n:], result.opakc_before[n:])
    )
    helper_order_ready = bool(len(result.helper_results) == 4)

    summary = {
        "gsmooth_translated": True,
        "gsmooth2_translated": True,
        "gsmooth_vtherm_direct_fortran_ready": vtherm_ready,
        "gsmooth_brcems_direct_fortran_ready": brcems_ready,
        "gsmooth_rccemis1_direct_fortran_ready": rcc1_ready,
        "gsmooth_rccemis2_direct_fortran_ready": rcc2_ready,
        "gsmooth_opakc_direct_fortran_ready": opakc_ready,
        "gsmooth_first_two_bins_unchanged_ready": first_two_ready,
        "gsmooth_high_energy_passthrough_ready": high_energy_ready,
        "gsmooth_caller_tail_ownership_ready": tails_ready,
        "gsmooth_helper_call_order_ready": helper_order_ready,
    }
    summary["gsmooth_direct_original_fortran_reference_ready"] = bool(
        all(value for key, value in summary.items() if key.endswith("_ready"))
    )
    return summary


