def _mg_type49_shadow_sample_score(sample: Mapping[str, Any], *, mode: str) -> float:
    keys = (
        ("scalar_pirt_abs_diff", "scalar_rrrt_abs_diff", "max_matrix_abs_diff")
        if str(mode) == "abs"
        else ("scalar_pirt_rel_diff", "scalar_rrrt_rel_diff", "max_matrix_rel_diff")
    )
