@dataclass
class ElementCompactBasis:
    """Exact compact element basis generated by ``calc_hmc_element`` rules."""

    element_z: int
    min_ion_stage: int
    max_ion_stage: int
    blocks: List[ElementIonBlock]
    rows: List[ElementBasisRow]
    n_rows: int
    n_superlevels: int
    n_ions: int
    normalization_row: int
    role_to_row: Dict[Tuple[int, int], int] = field(default_factory=dict)
    ion_stage_by_counter: Dict[int, int] = field(default_factory=dict)

    def row(self, compact_index: int) -> ElementBasisRow:
        if compact_index < 1 or compact_index > self.n_rows:
            raise IndexError(f"compact row {compact_index} outside 1..{self.n_rows}")
        return self.rows[compact_index - 1]

    def endpoint_row(self, ion_index: int, local_endpoint: int) -> int:
        block = next((b for b in self.blocks if b.ion_index == int(ion_index)), None)
        if block is None:
            raise KeyError(f"ion index {ion_index} is not in the compact basis")
        row = block.compact_index(local_endpoint)
        if row < 1 or row > self.n_rows:
            raise IndexError(
                f"ion {ion_index} local endpoint {local_endpoint} maps to compact row {row}, "
                f"outside 1..{self.n_rows}"
            )
        return row

    @property
    def nsup(self) -> np.ndarray:
        out = np.zeros(self.n_rows + 1, dtype=np.int32)
        for row in self.rows:
            out[row.compact_index] = row.superlevel
        return out

    @property
    def nion(self) -> np.ndarray:
        """One-based compact ion-block counters used internally by ``msolvelucy``."""
        out = np.zeros(self.n_rows + 1, dtype=np.int32)
        for row in self.rows:
            out[row.compact_index] = row.ion_counter
        return out

    @property
    def ion_stage(self) -> np.ndarray:
        """Physical ion stage for each compact row, matching XSTAR probe ``nion``.

        ``calc_hmc_element`` overwrites a shared parent-continuum/next-ground
        compact row when the following ion block is installed.  Therefore a
        shared alias takes the ion stage of its next-ion ground role, i.e. the
        largest physical ion stage among its roles.  This is distinct from the
        compact block counter returned by :attr:`nion`.
        """
        out = np.zeros(self.n_rows + 1, dtype=np.int32)
        for row in self.rows:
            stages = [int(role.get("ion_stage", 0)) for role in row.roles if int(role.get("ion_stage", 0)) > 0]
            if stages:
                out[row.compact_index] = max(stages)
            elif row.ion_counter > 0:
                out[row.compact_index] = int(
                    self.ion_stage_by_counter.get(
                        row.ion_counter, self.min_ion_stage + row.ion_counter - 1
                    )
                )
        return out


@dataclass(frozen=True)
class EscapeProbabilityContext:
    """Line/RRC optical-depth state used by ``calc_hmc_ion``.

    Arrays are one-based conceptually but are passed as ordinary zero-based
    NumPy sequences.  Missing entries are treated as optically thin only when
    ``allow_missing_as_zero`` is true; otherwise the affected record is
    reported as context blocked.
    """

    line_tau_in: Optional[np.ndarray] = None
    line_tau_out: Optional[np.ndarray] = None
    continuum_tau_in: Optional[np.ndarray] = None
    continuum_tau_out: Optional[np.ndarray] = None
    allow_missing_as_zero: bool = False

    @staticmethod
    def _value(values: Optional[np.ndarray], index: int) -> Optional[float]:
        if values is None or index <= 0 or index > len(values):
            return None
        value = float(values[index - 1])
        return value if math.isfinite(value) else None

    def line_taus(self, index: int) -> Tuple[Optional[float], Optional[float]]:
        return self._value(self.line_tau_in, index), self._value(self.line_tau_out, index)

    def continuum_taus(self, index: int) -> Tuple[Optional[float], Optional[float]]:
        return self._value(self.continuum_tau_in, index), self._value(self.continuum_tau_out, index)


