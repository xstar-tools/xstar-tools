"""Source-faithful element statistical-equilibrium subsystem.

This module translates the execution sequence

``levwkelement -> calc_hmc_ion -> calc_hmc_element -> msolvelucy``

as one coherent Python subsystem.  It preserves XSTAR's one-based compact
``ipmat2`` topology, including the shared identity between an ion's continuum
row and the next ion's ground row, traverses records through the pointer tables
built by :mod:`xstar_tools.xstar.atomic_database`, inserts the four
matrix rows emitted by ``calc_hmc_ion.f90``, and solves populations with the
Lucy superlevel iteration from ``msolvelucy.f90``.

The implementation is deliberately array-oriented and source named.  It does
not use historical probe matrices or fitted source terms.  A record that lacks
required plasma, level, escape, or radiation context is reported explicitly
and prevents the strict direct-solve readiness gate.
"""
