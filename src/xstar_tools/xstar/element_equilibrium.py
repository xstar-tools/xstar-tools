def pescl(tau: float) -> float:
    """Translate ``pescl.f90`` line escape probability."""
    tau = float(tau)
    tauw = 1.0e5
    if tau < 1.0:
        if tau < 1.0e-5:
            value = 1.0
        else:
            aa = 2.0 * tau
            value = (1.0 - math.exp(-aa)) / aa
    else:
        bb = 0.5 * math.sqrt(max(math.log(tau), 0.0)) / (1.0 + tau / tauw)
        value = 1.0 / (tau * math.sqrt(math.pi) * (1.2 + bb))
    return value / 2.0


def pescv(tau: float) -> float:
    """Translate ``pescv.f90`` RRC escape probability."""
    return max(math.exp(-float(tau)), 1.0e-12) / 2.0


def _iter_ion_records(derived: XSTARDerivedPointers, element_z: int) -> Iterator[Tuple[int, int, int]]:
    for ion_index in range(1, derived.n_ions + 1):
        if int(derived.ion_element_z[ion_index]) == int(element_z):
            yield ion_index, int(derived.ion_stage[ion_index]), int(derived.ion_records[ion_index])


def _record_label(master: XSTARMasterData, record: int) -> str:
    try:
        return master.record_chars(record).decode("latin-1", errors="replace").strip("\x00 ")
    except Exception:
        return ""


_LEVEL_TABLE_CACHE: Dict[Tuple[int, int, int], UCalcLevelTable] = {}


def clear_level_table_cache() -> None:
    """Clear the process-local level-table cache used by hot Mg/Ca loops."""
    _LEVEL_TABLE_CACHE.clear()


def build_level_table(
    master: XSTARMasterData,
    derived: XSTARDerivedPointers,
    ion_index: int,
) -> UCalcLevelTable:
    """Translate ``calc_rates_level_lte`` record unpacking for one ion.

    v0.5.46 caches the immutable per-ion level table by the master/derived
    object identity and ion index.  Mg/Ca high-density runs repeatedly rebuild
    the same Z=12/Z=20 level tables inside ``calc_hmc_all`` and
    ``calc_emis_all``; caching preserves source semantics while removing a
    pure Python record-scan from the hottest element loops.
    """
    cache_key = (id(master), id(derived), int(ion_index))
    cached = _LEVEL_TABLE_CACHE.get(cache_key)
    if cached is not None:
        return cached
    nlev = int(derived.nlevs[ion_index])
    ion_record = int(derived.ion_records[ion_index])
    levels: Dict[int, UCalcLevel] = {}
    rec = int(derived.npfi[13, ion_index])
    while rec and int(derived.npar[rec]) == ion_record:
        header = master.header(rec)
        if header.rate_type == 13:
            reals = master.record_reals(rec)
            ints = master.record_integers(rec)
            if len(ints) >= 2:
                local = int(ints[-2])
                if 1 <= local <= nlev:
                    energy = float(reals[0]) if len(reals) > 0 else 0.0
                    weight = float(reals[1]) if len(reals) > 1 else 0.0
                    ionpot = float(reals[3]) if len(reals) > 3 else energy
                    levels[local] = UCalcLevel(
                        index=local,
                        energy_ev=energy,
                        statistical_weight=weight,
                        ionization_potential_ev=ionpot,
                        continuum_energy_ev=energy,
                        principal_n=int(ints[0]) if len(ints) > 0 else None,
                        orbital_l=int(ints[2]) if len(ints) > 2 else None,
                        label=_record_label(master, rec),
                    )
        rec = int(derived.npnxt[rec]) if rec else 0
    missing = [i for i in range(1, nlev + 1) if i not in levels]
    if missing:
        raise ElementEquilibriumError(
            f"ion index {ion_index} is missing level records {missing[:8]}"
            + ("..." if len(missing) > 8 else "")
        )
    table = UCalcLevelTable(levels=levels, nlev=nlev)
    _LEVEL_TABLE_CACHE[cache_key] = table
    return table


def _copy_level_table(table: UCalcLevelTable) -> UCalcLevelTable:
    """Copy the mutable Fortran ``leveltemp`` workspace state.

    ``calc_rates_level_lte`` overwrites only columns ``1:nlev`` of the shared
    work array.  Entries above the current ion's ``nlev`` therefore retain
    values from the previously processed ion.  A shallow copy is sufficient
    because :class:`UCalcLevel` instances are immutable.
    """

    return UCalcLevelTable(levels=dict(table.levels), nlev=int(table.nlev))


def _overwrite_leveltemp_workspace(
    workspace: UCalcLevelTable,
    current: UCalcLevelTable,
    *,
    owner_by_column: Optional[Dict[int, Dict[str, Any]]] = None,
    owner_ion_index: Optional[int] = None,
    owner_ion_stage: Optional[int] = None,
    write_sequence: Optional[int] = None,
    phase: str = "second_pass",
) -> UCalcLevelTable:
    """Apply one source-faithful ``calc_rates_level_lte`` overwrite.

    The current ion replaces workspace columns ``1:nlev`` while any higher
    columns remain untouched.  ``workspace.nlev`` still records the current
    ion dimension, matching the separate Fortran ``nlev`` argument.

    ``owner_by_column`` is diagnostic-only provenance for the retained work
    array.  It records which ion most recently wrote each column; it never
    changes the numerical source semantics.
    """

    nlev = int(current.nlev)
    for index in range(1, nlev + 1):
        workspace.levels[index] = current.require(index)
        if owner_by_column is not None:
            owner_by_column[index] = {
                "ion_index": int(owner_ion_index or 0),
                "ion_stage": int(owner_ion_stage or 0),
                "nlev": nlev,
                "write_sequence": int(write_sequence or 0),
                "phase": str(phase),
            }
    workspace.nlev = nlev
    return workspace


def _initialize_leveltemp_workspace_from_levwkelement(
    basis: "ElementCompactBasis",
    level_tables: Mapping[int, UCalcLevelTable],
    *,
    initial_workspace: Optional[UCalcLevelTable] = None,
    initial_owner_by_column: Optional[Mapping[int, Mapping[str, Any]]] = None,
) -> tuple[UCalcLevelTable, Dict[int, Dict[str, Any]], List[Dict[str, Any]]]:
    """Replay the mutable ``leveltemp`` writes performed by ``levwkelement``.

    ``levwkelement.f90`` calls ``calc_rates_level_lte`` for every active ion
    in ascending source order.  That routine overwrites only ``1:nlev`` and
    does not clear higher columns.  The array entering the second element pass
    is therefore a composite workspace, not a clean copy of the final ion.
    """

    if not basis.blocks:
        raise ElementEquilibriumError("cannot initialize leveltemp without active ion blocks")
    # ``leveltemp%rlev`` is a fixed ``(10,ndl)`` Fortran work array.  It is
    # zero-initialized before the active-ion writes used by this bounded
    # fixed-state replay.  Columns never touched by ``calc_rates_level_lte``
    # therefore remain addressable zeros rather than absent Python entries.
    if initial_workspace is None:
        workspace = UCalcLevelTable(
            levels={
                index: UCalcLevel(index=index)
                for index in range(1, XSTAR_LEVELTEMP_NDL + 1)
            },
            nlev=0,
        )
    else:
        workspace = _copy_level_table(initial_workspace)
        # The Fortran array is always addressable through ``ndl``.  Populate
        # absent Python columns with source-zero entries without disturbing
        # retained columns supplied by the caller.
        for index in range(1, XSTAR_LEVELTEMP_NDL + 1):
            workspace.levels.setdefault(index, UCalcLevel(index=index))

    owner_by_column: Dict[int, Dict[str, Any]] = {}
    for index in range(1, XSTAR_LEVELTEMP_NDL + 1):
        supplied = None if initial_owner_by_column is None else initial_owner_by_column.get(index)
        if supplied is None:
            owner_by_column[index] = {
                "ion_index": 0,
                "ion_stage": 0,
                "nlev": 0,
                "write_sequence": 0,
                "phase": (
                    "initial_unwritten_zero"
                    if initial_workspace is None
                    else "incoming_workspace_unattributed"
                ),
            }
        else:
            owner_by_column[index] = dict(supplied)

    trace: List[Dict[str, Any]] = []
    if initial_workspace is not None:
        trace.append({
            "phase": "incoming_leveltemp_workspace",
            "write_sequence": 0,
            "ion_index": 0,
            "ion_stage": 0,
            "nlev_written": 0,
            "workspace_max_column_before": max(workspace.levels, default=0),
            "workspace_max_column_after": max(workspace.levels, default=0),
            "n_retained_higher_columns": sum(
                1 for value in owner_by_column.values()
                if int(value.get("write_sequence", 0)) > 0
                or str(value.get("phase", "")).startswith("incoming")
            ),
            "incoming_workspace_present": True,
        })
    for sequence, block in enumerate(basis.blocks, start=1):
        current = level_tables[block.ion_index]
        previous_max = max(workspace.levels, default=0)
        _overwrite_leveltemp_workspace(
            workspace,
            current,
            owner_by_column=owner_by_column,
            owner_ion_index=block.ion_index,
            owner_ion_stage=block.ion_stage,
            write_sequence=sequence,
            phase="levwkelement",
        )
        trace.append({
            "phase": "levwkelement",
            "write_sequence": sequence,
            "ion_index": block.ion_index,
            "ion_stage": block.ion_stage,
            "nlev_written": current.nlev,
            "workspace_max_column_before": previous_max,
            "workspace_max_column_after": max(workspace.levels, default=0),
            "n_retained_higher_columns": max(0, previous_max - current.nlev),
        })
    return workspace, owner_by_column, trace


def build_element_compact_basis(
    master: XSTARMasterData,
    derived: XSTARDerivedPointers,
    *,
    element_z: int,
    min_ion_stage: int,
    max_ion_stage: int,
) -> ElementCompactBasis:
    """Translate the compact ``ipmat/ipmat2/nsup/nion`` basis construction."""
    # ``calc_hmc_element.f90`` increments ``nionp`` for every ion of the
    # element before applying the active-stage limits.  Preserve those source
    # counters even when the compact matrix contains only a selected subset.
    all_element_ions = sorted(_iter_ion_records(derived, element_z), key=lambda x: x[1])
    source_counter_by_ion = {
        int(ion_index): counter
        for counter, (ion_index, _stage, _record) in enumerate(all_element_ions, start=1)
    }
    ion_stage_by_counter = {
        counter: int(stage)
        for counter, (_ion_index, stage, _record) in enumerate(all_element_ions, start=1)
    }
    selected = [
        (idx, stage, rec)
        for idx, stage, rec in all_element_ions
        if min_ion_stage <= stage <= max_ion_stage
    ]
    if not selected:
        raise ElementEquilibriumError(
            f"no ions for Z={element_z} in stage range {min_ion_stage}..{max_ion_stage}"
        )

    blocks: List[ElementIonBlock] = []
    rows_by_index: Dict[int, ElementBasisRow] = {}
    role_to_row: Dict[Tuple[int, int], int] = {}
    ipmat2 = 0
    nsp = 1
    nionp = len(all_element_ions)

    for ion_index, stage, ion_record in selected:
        source_ion_counter = int(source_counter_by_ion[ion_index])
        nlev = int(derived.nlevs[ion_index])
        if nlev <= 0:
            raise ElementEquilibriumError(f"ion index {ion_index} has invalid nlev={nlev}")
        start = ipmat2 + 1
        stop = ipmat2 + nlev
        block = ElementIonBlock(
            ion_index=ion_index,
            ion_record=ion_record,
            element_z=element_z,
            ion_stage=stage,
            nlev=nlev,
            compact_start=start,
            compact_stop=stop,
            first_level_record=int(derived.npfi[13, ion_index]),
            ion_counter=source_ion_counter,
            label=_record_label(master, ion_record),
        )
        blocks.append(block)

        # Ground row.  If shared with the previous ion continuum, the newer
        # spectroscopic-ground role determines nsup/nion exactly as in Fortran.
        ground = rows_by_index.setdefault(start, ElementBasisRow(start))
        ground.superlevel = nsp
        ground.ion_counter = source_ion_counter

        if nlev > 2:
            nsp += 1
            for local in range(2, nlev):
                row_index = start + local - 1
                row = rows_by_index.setdefault(row_index, ElementBasisRow(row_index))
                row.superlevel = nsp
                row.ion_counter = source_ion_counter
        nsp += 1

        for local in range(1, nlev + 1):
            row_index = start + local - 1
            row = rows_by_index.setdefault(row_index, ElementBasisRow(row_index))
            role = {
                "ion_index": ion_index,
                "ion_stage": stage,
                "local_level": local,
                "role": (
                    "ground"
                    if local == 1
                    else "parent_continuum_or_next_ground"
                    if local == nlev
                    else "spectroscopic_or_superlevel"
                ),
                "ion_record": ion_record,
                "ion_counter": source_ion_counter,
            }
            row.roles.append(role)
            role_to_row[(ion_index, local)] = row_index

        ipmat2 += nlev - 1

    n_rows = ipmat2 + 1
    final_row = rows_by_index.setdefault(n_rows, ElementBasisRow(n_rows))
    final_row.superlevel = nsp
    final_row.ion_counter = nionp

    rows: List[ElementBasisRow] = []
    for index in range(1, n_rows + 1):
        row = rows_by_index.get(index)
        if row is None:
            raise ElementEquilibriumError(f"compact row {index} was not instantiated")
        if row.superlevel <= 0:
            # This can only be a final continuum role before its shared next-ion
            # ground role is seen; the final row is assigned above.
            row.superlevel = nsp
            row.ion_counter = nionp
        rows.append(row)

    return ElementCompactBasis(
        element_z=element_z,
        min_ion_stage=min_ion_stage,
        max_ion_stage=max_ion_stage,
        blocks=blocks,
        rows=rows,
        n_rows=n_rows,
        n_superlevels=nsp,
        n_ions=nionp,
        normalization_row=n_rows,
        role_to_row=role_to_row,
        ion_stage_by_counter=ion_stage_by_counter,
    )




def map_global_populations_to_compact_basis(
    basis: ElementCompactBasis,
    global_populations: Mapping[Tuple[int, int, int], float],
    *,
    terminal_continuum_seed_mode: str = "source-zero",
) -> np.ndarray:
    """Map source global ``xilevg`` state onto one current compact basis.

    The selected-ion mapping follows the literal ``calc_hmc_element.f90``
    order: each ion writes all ``nlev`` values and advances by ``nlev-1``, so
    the next-ion ground overwrites the shared previous-ion continuum row.
    After that loop the source executes ``x(ipmat2+1)=0.``; therefore the
    final compact continuum/normalization row is *not* seeded from global
    ``xilevg``.  ``legacy-global`` is retained only to reproduce the
    pre-v0.4.55 diagnostic behavior.

    Missing global entries are exact zero, matching the initialized XSTAR
    workspace.  The returned array includes the one-based guard at index zero.
    """

    if terminal_continuum_seed_mode not in {"source-zero", "legacy-global"}:
        raise ElementEquilibriumError(
            "terminal_continuum_seed_mode must be 'source-zero' or "
            "'legacy-global'"
        )
    mapped = np.zeros(basis.n_rows + 1, dtype=float)
    for block in basis.blocks:
        for local_level in range(1, block.nlev + 1):
            key = (int(basis.element_z), int(block.ion_stage), int(local_level))
            value = float(global_populations.get(key, 0.0))
            if not math.isfinite(value) or value < 0.0:
                raise ElementEquilibriumError(
                    f"invalid global initial population for {key}: {value}"
                )
            mapped[block.compact_index(local_level)] = value
    if terminal_continuum_seed_mode == "source-zero":
        mapped[basis.normalization_row] = 0.0
    return mapped

def levwk(levels: UCalcLevelTable, context: ElementEquilibriumContext) -> np.ndarray:
    """Translate ``levwk.f90`` for one ion."""
    nlev = levels.nlev
    if nlev < 1:
        raise ElementEquilibriumError("levwk requires at least one level")
    tm = float(context.temperature_k)
    if tm <= 0:
        raise ElementEquilibriumError("temperature must be positive")
    xnx = float(context.electron_density_cm3)
    # bk/ergsev in XSTAR is 8.61707e-5 eV K^-1.
    bktm = 8.61707e-5 * tm
    q2 = 2.07e-16 * xnx * tm ** (-1.5)
    continuum = levels.require(nlev)
    emlt_cont = continuum.statistical_weight
    if emlt_cont <= 0:
        raise ElementEquilibriumError(f"continuum level {nlev} has non-positive statistical weight")
    rs = q2 / emlt_cont
    ethion = continuum.energy_ev
    rniss = np.zeros(nlev + 1, dtype=float)
    rniss[nlev] = 1.0
    bb = 1.0
    for local in range(1, nlev):
        level = levels.require(local)
        ethsht = max((ethion - level.energy_ev) / max(bktm, 1.0e-300), 0.0)
        explev2 = math.exp(max(-ethsht, -60.0))
        rniss[local] = level.statistical_weight / (explev2 / max(rs, 1.0e-300))
        bb += rniss[local]
    rniss[1:] /= max(bb, 1.0e-300)
    return rniss


def levwkelement(
    master: XSTARMasterData,
    derived: XSTARDerivedPointers,
    basis: ElementCompactBasis,
    context: ElementEquilibriumContext,
) -> Tuple[np.ndarray, Dict[int, UCalcLevelTable]]:
    """Translate ``levwkelement.f90`` and normalize the element seed."""
    rnise = np.zeros(basis.n_rows + 1, dtype=float)
    level_tables: Dict[int, UCalcLevelTable] = {}
    ipmatsv = 0
    last_rnisi: Optional[np.ndarray] = None
    last_nlev = 0

    for block in basis.blocks:
        levels = build_level_table(master, derived, block.ion_index)
        level_tables[block.ion_index] = levels
        rnisi = levwk(levels, context)
        last_rnisi = rnisi
        last_nlev = block.nlev
        if block.ion_stage == basis.min_ion_stage:
            rnise[1 + ipmatsv] = rnisi[1]
        for local in range(2, block.nlev + 1):
            target = local + ipmatsv
            if block.ion_stage > basis.min_ion_stage:
                rnise[target] = min(
                    1.0e66,
                    rnise[target - 1] * rnisi[local] / (1.0e-37 + rnisi[local - 1]),
                )
            else:
                rnise[target] = rnisi[local]
        ipmatsv += block.nlev - 1

    if last_rnisi is None or last_nlev < 2:
        raise ElementEquilibriumError("cannot construct fully stripped element population")
    rnise[ipmatsv + 1] = (
        rnise[ipmatsv] * last_rnisi[last_nlev] / (1.0e-97 + last_rnisi[last_nlev - 1])
    )
    total = float(np.sum(rnise[1 : basis.n_rows + 1]))
    if total <= 0 or not math.isfinite(total):
        raise ElementEquilibriumError("levwkelement produced a non-positive normalization")
    rnise[1 : basis.n_rows + 1] /= total
    return rnise, level_tables


def _escape_factors(
    record: int,
    rate_type: int,
    derived: XSTARDerivedPointers,
    context: ElementEquilibriumContext,
) -> Tuple[float, float, Optional[str]]:
    ptmp1 = 0.5
    ptmp2 = 0.5
    if rate_type == 4:
        index = int(derived.nplini[record]) if record < len(derived.nplini) else 0
        tau1, tau2 = context.escape.line_taus(index)
        if tau1 is None or tau2 is None:
            if context.escape.allow_missing_as_zero:
                tau1 = tau2 = 0.0
            else:
                return ptmp1, ptmp2, f"missing_line_optical_depth_for_line_index_{index}"
        ptmp1 = pescl(tau1) * (1.0 - context.covering_fraction)
        ptmp2 = (
            pescl(tau2) * (1.0 - context.covering_fraction)
            + 2.0 * pescl(tau1 + tau2) * context.covering_fraction
        )
    elif rate_type == 7:
        index = int(derived.npconi2[record]) if record < len(derived.npconi2) else 0
        tau1, tau2 = context.escape.continuum_taus(index)
        if tau1 is None or tau2 is None:
            if context.escape.allow_missing_as_zero:
                tau1 = tau2 = 0.0
            else:
                return ptmp1, ptmp2, f"missing_continuum_optical_depth_for_index_{index}"
        ptmp1 = pescv(tau1) * (1.0 - context.covering_fraction)
        ptmp2 = (
            pescv(tau2) * (1.0 - context.covering_fraction)
            + 2.0 * pescv(tau1 + tau2) * context.covering_fraction
        )
    return ptmp1, ptmp2, None


def _endpoint_energy(levels: UCalcLevelTable, endpoint: int) -> Optional[float]:
    level = levels.get(endpoint)
    return None if level is None else float(level.energy_ev)


def _lower_upper(result: UCalcResult, levels: UCalcLevelTable) -> Tuple[int, int]:
    id1, id2 = int(result.idest1), int(result.idest2)
    lower, upper = id1, id2
    if id1 <= 0 or id2 <= 0:
        return lower, upper
    if result.rate_type not in {7, 41}:
        e1 = _endpoint_energy(levels, id1)
        e2 = _endpoint_energy(levels, id2)
        if e1 is not None and e2 is not None:
            if (e1 / (1.0e-24 + e2) - 1.0) < 1.0e-8:
                upper, lower = id2, id1
            else:
                upper, lower = id1, id2
    return lower, upper



