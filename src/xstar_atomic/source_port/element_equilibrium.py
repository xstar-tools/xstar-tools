class ElementEquilibriumError(RuntimeError):
    """Raised when a source-faithful element matrix cannot be constructed."""


@dataclass(frozen=True)
class ElementIonBlock:
    """One ion block in the compact ``ipmat2`` element basis."""

    ion_index: int
    ion_record: int
