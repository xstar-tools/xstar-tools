def _write_csv(path: Path, rows: Sequence[Mapping[str, Any]], fieldnames: Sequence[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def write_element_equilibrium_products(
    result: ElementEquilibriumResult,
    out_dir: str | Path,
    *,
    port_version: str = "v0.4.16",
) -> Dict[str, Path]:
    """Write basis, matrix, population, blocker, and summary products."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    assembly = result.assembly
    basis = assembly.basis
    solve = result.solve

    basis_rows: List[Dict[str, Any]] = []
    for row in basis.rows:
        basis_rows.append(
            {
                "compact_index": row.compact_index,
                "superlevel": row.superlevel,
                "ion_counter": row.ion_counter,
                "n_roles": len(row.roles),
                "is_shared_alias": row.is_shared_alias,
                "roles_json": json.dumps(row.roles, sort_keys=True),
            }
        )
    basis_csv = out / "xstar_element_compact_basis.csv"
    _write_csv(basis_csv, basis_rows, list(basis_rows[0]) if basis_rows else [])

    terms_rows = [term.__dict__ for term in assembly.terms]
    terms_csv = out / "xstar_element_matrix_terms.csv"
    _write_csv(terms_csv, terms_rows, list(terms_rows[0]) if terms_rows else ["term_index"])

    ion_rows = []
    for summary in assembly.ion_summaries:
        row = dict(summary.__dict__)
        row["blocked_reasons"] = json.dumps(summary.blocked_reasons, sort_keys=True)
        ion_rows.append(row)
    ions_csv = out / "xstar_element_ion_assembly.csv"
    _write_csv(ions_csv, ion_rows, list(ion_rows[0]) if ion_rows else ["ion_index"])

    blocked_csv = out / "xstar_element_blocked_records.csv"
    blocked_fields = sorted({key for row in assembly.blocked_records for key in row}) or ["record", "reason"]
    _write_csv(blocked_csv, assembly.blocked_records, blocked_fields)

    populations_rows: List[Dict[str, Any]] = []
    for i, row in enumerate(basis.rows, start=1):
        populations_rows.append(
            {
                "compact_index": i,
                "initial_population": float(assembly.initial_populations[i]),
                "solved_population": "" if solve is None else float(solve.populations[i - 1]),
                "superlevel": row.superlevel,
                "ion_counter": row.ion_counter,
                "roles_json": json.dumps(row.roles, sort_keys=True),
            }
        )
    populations_csv = out / "xstar_element_populations.csv"
    _write_csv(populations_csv, populations_rows, list(populations_rows[0]) if populations_rows else [])

    residual_rows: List[Dict[str, Any]] = []
    if solve is not None:
        for i, row in enumerate(basis.rows):
            residual_rows.append(
                {
                    "compact_index": i + 1,
                    "superlevel": row.superlevel,
                    "ion_counter": row.ion_counter,
                    "population": float(solve.populations[i]),
                    "absolute_row_residual": float(abs(solve.row_residual[i])),
                    "signed_row_residual": float(solve.row_residual[i]),
                    "row_equation_scale": float(solve.row_scale[i]),
                    "relative_row_residual": float(solve.relative_row_residual[i]),
                    "active_scale_gt_1e_12": bool(solve.row_scale[i] > 1.0e-12),
                    "zero_scale_row": bool(solve.row_scale[i] <= 1.0e-300),
                }
            )
    residuals_csv = out / "xstar_element_row_residuals.csv"
    _write_csv(
        residuals_csv,
        residual_rows,
        list(residual_rows[0]) if residual_rows else ["compact_index"],
    )

    trace_outputs: Dict[str, Path] = {}
    if solve is not None and solve.trace is not None:
        trace_specs = [
            ("lucy_outer_trace_csv", "xstar_msolvelucy_outer_level_trace.csv", solve.trace.outer_level_rows),
            ("lucy_superlevel_trace_csv", "xstar_msolvelucy_superlevel_trace.csv", solve.trace.superlevel_rows),
            ("lucy_condensed_matrix_trace_csv", "xstar_msolvelucy_condensed_matrix_trace.csv", solve.trace.condensed_matrix_rows),
            ("lucy_fixed_point_trace_csv", "xstar_msolvelucy_fixed_point_trace.csv", solve.trace.fixed_point_rows),
        ]
        for key, filename, rows in trace_specs:
            path = out / filename
            _write_csv(path, rows, list(rows[0]) if rows else ["status"])
            trace_outputs[key] = path

    matrix_npz = out / "xstar_element_matrix.npz"
    np.savez_compressed(
        matrix_npz,
        matrix=assembly.dense_matrix,
        normalized_matrix=assembly.normalized_matrix,
        rhs=assembly.rhs,
        heating_matrix=assembly.heating_matrix,
        heating_matrix2=assembly.heating_matrix2,
        initial_populations=assembly.initial_populations[1:],
        solved_populations=np.asarray([] if solve is None else solve.populations),
        gamma=np.asarray([] if solve is None else solve.gamma),
        alpha=np.asarray([] if solve is None else solve.alpha),
        fgamma=np.asarray([] if solve is None else solve.fgamma),
        falpha=np.asarray([] if solve is None else solve.falpha),
        ion_population_totals=np.asarray([] if solve is None else solve.ion_population_totals),
        ionization_totals=np.asarray([] if solve is None else solve.ionization_totals),
        recombination_totals=np.asarray([] if solve is None else solve.recombination_totals),
        ionization_components=np.asarray([] if solve is None else solve.ionization_components),
        recombination_components=np.asarray([] if solve is None else solve.recombination_components),
        row_residual=np.asarray([] if solve is None else solve.row_residual),
        row_scale=np.asarray([] if solve is None else solve.row_scale),
        relative_row_residual=np.asarray([] if solve is None else solve.relative_row_residual),
        nsup=basis.nsup[1:],
        nion=basis.nion[1:],
    )

    summary: Dict[str, Any] = {
        "port_version": port_version,
        "status": "element_statistical_equilibrium_subsystem_completed",
        "element_z": basis.element_z,
        "min_ion_stage": basis.min_ion_stage,
        "max_ion_stage": basis.max_ion_stage,
        "n_compact_rows": basis.n_rows,
        "n_ion_blocks": len(basis.blocks),
        "n_superlevels": basis.n_superlevels,
        "normalization_row": basis.normalization_row,
        "n_shared_alias_rows": sum(row.is_shared_alias for row in basis.rows),
        "n_records_seen": assembly.n_records_seen,
        "n_records_evaluated": assembly.n_records_evaluated,
        "n_records_source_noop": assembly.n_records_source_noop,
        "n_records_skipped": assembly.n_records_skipped,
        "n_records_blocked": assembly.n_records_blocked,
        "n_unmapped_matrix_endpoints": assembly.n_unmapped_endpoints,
        "n_source_ipmat_endpoint_clamps": assembly.n_source_ipmat_endpoint_clamps,
        "n_matrix_terms": len(assembly.terms),
        "strict_matrix_assembly_ready": assembly.strict_assembly_ready,
        "source_sequence_complete": result.source_sequence_complete,
        "full_element_direct_solve_ready": result.full_element_direct_solve_ready,
        "six_row_and_119_row_products_role": "regression_subsets_only",
        "production_acceptance_target": f"full_{basis.n_rows}_row_element_matrix_and_population_vector",
    }
    parity = result.population_parity
    matrix_parity = result.full_element_matrix_parity
    if not assembly.strict_assembly_ready:
        dominant_next_target = "resolve_remaining_element_matrix_assembly_blockers"
    elif solve is None:
        dominant_next_target = "execute_full_element_population_solve"
    elif not solve.converged or solve.n_negative_populations > 0:
        dominant_next_target = "resolve_msolvelucy_convergence"
    elif not result.full_element_direct_solve_ready:
        dominant_next_target = "resolve_full_element_execution_acceptance"
    elif matrix_parity is not None and not matrix_parity.full_element_matrix_parity_ready:
        dominant_next_target = matrix_parity.diagnosis
    elif parity is None:
        dominant_next_target = "run_xstar_population_parity_gate_before_generalization"
    elif not parity.xstar_population_parity_ready:
        dominant_next_target = parity.diagnosis
    elif result.msolvelucy_state_parity is None:
        dominant_next_target = "run_msolvelucy_iteration_state_parity_before_generalization"
    elif not result.msolvelucy_state_parity.msolvelucy_state_parity_ready:
        dominant_next_target = result.msolvelucy_state_parity.diagnosis
    else:
        dominant_next_target = "generalize_population_validated_element_solve_then_local_ionization_thermal_closure"
    summary["dominant_next_target"] = dominant_next_target
    summary["full_element_matrix_parity_supplied"] = matrix_parity is not None
    summary["full_element_matrix_parity_ready"] = bool(
        matrix_parity and matrix_parity.full_element_matrix_parity_ready
    )
    if matrix_parity is not None:
        summary["full_element_matrix_parity_diagnosis"] = matrix_parity.diagnosis
        summary["full_element_matrix_first_failing_data_type"] = matrix_parity.first_failing_data_type
        summary["full_element_matrix_first_failing_rate_type"] = matrix_parity.first_failing_rate_type
    summary["xstar_population_parity_supplied"] = parity is not None
    summary["xstar_population_parity_ready"] = bool(parity and parity.xstar_population_parity_ready)
    summary["milestone3_population_parity_ready"] = bool(parity and parity.xstar_population_parity_ready)
    if parity is not None:
        summary["population_parity_diagnosis"] = parity.diagnosis
        summary["selected_xstar_solve_call_id"] = parity.reference.solve_call_id
        summary["python_initial_vs_xstar_before_l1"] = parity.initial_metrics.l1_difference
        summary["python_native_final_vs_xstar_after_l1"] = parity.native_final_metrics.l1_difference
        summary["python_xstar_before_seeded_final_vs_xstar_after_l1"] = (
            None if parity.seeded_final_metrics is None else parity.seeded_final_metrics.l1_difference
        )
    state_parity = result.msolvelucy_state_parity
    summary["msolvelucy_state_parity_supplied"] = state_parity is not None
    summary["msolvelucy_state_parity_ready"] = bool(state_parity and state_parity.msolvelucy_state_parity_ready)
    if state_parity is not None:
        summary["msolvelucy_state_parity_diagnosis"] = state_parity.diagnosis
        summary["msolvelucy_first_failing_component"] = state_parity.first_failing_component
        summary["msolvelucy_first_failing_comparison_key"] = state_parity.first_failing_comparison_key
        summary["msolvelucy_first_failing_outer_iteration"] = state_parity.first_failing_outer_iteration
        summary["msolvelucy_first_failing_fixed_iteration"] = state_parity.first_failing_fixed_iteration

    if solve is not None:
        summary.update(
            {
                "solver_converged": solve.converged,
                "solver_method": solve.solver_method,
                "outer_iterations": solve.outer_iterations,
                "fixed_point_iterations": solve.fixed_point_iterations,
                "final_outer_difference": solve.final_outer_difference,
                "final_fixed_point_difference": solve.final_fixed_point_difference,
                "n_negative_populations": solve.n_negative_populations,
                "population_normalization": solve.normalization,
                "population_normalization_error": solve.normalization_error,
                "max_relative_row_residual": solve.max_relative_row_residual,
                "max_active_relative_row_residual": solve.max_active_relative_row_residual,
                "l1_row_residual": solve.l1_row_residual,
                "l1_relative_row_residual": solve.l1_relative_row_residual,
                "n_zero_scale_rows": solve.n_zero_scale_rows,
                "lucy_trace_captured": solve.trace is not None,
                "condensed_matrix_rank": solve.condensed_rank,
                "condensed_matrix_dimension": solve.condensed_dimension,
                "dense_normalized_matrix_rank": solve.dense_rank,
                "dense_normalized_matrix_condition_number": solve.dense_condition_number,
                "heating": solve.heating,
                "cooling": solve.cooling,
                "heating2": solve.heating2,
                "cooling2": solve.cooling2,
                "solver_notes": solve.notes,
            }
        )
    else:
        summary.update({"solver_converged": False, "solver_status": "not_run_due_to_incomplete_strict_assembly"})

    json_path = out / "xstar_element_equilibrium_summary.json"
    json_path.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    markdown_path = out / "xstar_element_equilibrium_summary.md"
    lines = [
        "# XSTAR source-faithful element statistical-equilibrium subsystem",
        "",
        f"- Port version: `{port_version}`",
        f"- Element Z: `{basis.element_z}`",
        f"- Ion stages: `{basis.min_ion_stage}`–`{basis.max_ion_stage}`",
        f"- Compact rows: `{basis.n_rows}`",
        f"- Shared alias rows: `{summary['n_shared_alias_rows']}`",
        f"- Matrix terms: `{len(assembly.terms)}`",
        f"- Blocked records: `{assembly.n_records_blocked}`",
        f"- Unmapped endpoints: `{assembly.n_unmapped_endpoints}`",
        f"- Source ipmat endpoint clamps: `{assembly.n_source_ipmat_endpoint_clamps}`",
        f"- Strict matrix assembly ready: `{assembly.strict_assembly_ready}`",
        f"- Solver converged: `{summary.get('solver_converged')}`",
        f"- Full direct solve ready: `{result.full_element_direct_solve_ready}`",
        f"- Full record-matrix parity ready: `{bool(matrix_parity and matrix_parity.full_element_matrix_parity_ready)}`",
        f"- XSTAR population parity supplied: `{parity is not None}`",
        f"- XSTAR population parity ready: `{bool(parity and parity.xstar_population_parity_ready)}`",
        f"- `msolvelucy` state parity ready: `{bool(result.msolvelucy_state_parity and result.msolvelucy_state_parity.msolvelucy_state_parity_ready)}`",
        f"- Dominant next target: `{dominant_next_target}`",
        "",
        "The six-row and 119-row products are retained only as regression subsets; "
        "the acceptance target is the complete compact element matrix and population vector.",
    ]
    markdown_path.write_text("\n".join(lines) + "\n")

    return {
        "basis_csv": basis_csv,
        "terms_csv": terms_csv,
        "ions_csv": ions_csv,
        "blocked_csv": blocked_csv,
        "populations_csv": populations_csv,
        "residuals_csv": residuals_csv,
        "matrix_npz": matrix_npz,
        "json": json_path,
        "markdown": markdown_path,
        **trace_outputs,
    }
